// Ratchets the number of type assertions per file against the recorded baseline.

import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';
import { REPOSITORY_ROOT } from './util/source-tree.ts';
import { countTypeAssertionsByFile } from './util/type-assertions.ts';

/**
 * No new type assertion is added to the library.
 *
 * A cast is a claim the author could not prove, and Biome cannot see one: `any` and `!` are rules,
 * but `value as SomeType` passes every check in the toolchain and still switches off the narrowing
 * that should have been written. AGENTS.md states the rule — "narrow the input instead, or make the
 * function return the type you actually meant" — and this is the mechanical half of it.
 *
 * The tree already holds casts, so a strict "none" cannot ship. Each file's count is accepted in
 * `scripts/type-assertion-baseline.json` rather than each cast, which is the smallest acceptance that
 * still fails a new one: adding an assertion to a file exceeds its count, and removing every
 * assertion from a file leaves the entry stale. The counter is regenerated by
 * `deno task type-assertions:baseline`, and is a count rather than a set so a rename near a cast does
 * not churn the file.
 */

/** The accepted assertion counts, keyed by repository-relative path. */
const BASELINE_PATH = join(REPOSITORY_ROOT, 'scripts', 'type-assertion-baseline.json');

const CURRENT = countTypeAssertionsByFile();
const BASELINE = JSON.parse(readFileSync(BASELINE_PATH, 'utf8')) as Readonly<
  Record<string, number>
>;

/** A file whose assertion count grew or shrank, with both numbers, for the report. */
function describeChange(path: string, before: number, after: number): string {
  return `${path}: ${before} accepted, ${after} found`;
}

describe('type assertions', () => {
  it('adds no assertion a file was not already allowed', () => {
    const added = Object.entries(CURRENT)
      .filter(([path, count]) => count > (BASELINE[path] ?? 0))
      .map(([path, count]) => describeChange(path, BASELINE[path] ?? 0, count));

    expect(added).toEqual([]);
  });

  it('keeps no accepted assertion that is no longer there', () => {
    const stale = Object.entries(BASELINE)
      .filter(([path, count]) => (CURRENT[path] ?? 0) < count)
      .map(([path, count]) => describeChange(path, count, CURRENT[path] ?? 0));

    expect(stale).toEqual([]);
  });
});
