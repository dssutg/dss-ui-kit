package main

import (
	"encoding/base64"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

func generate(filename string) {
	fmt.Printf("Generating TS module for %s...\n", filename)

	// Get the current script directory
	currentScriptDirectory, err := os.Getwd()
	if err != nil {
		fmt.Println("Error getting current directory:", err)
		return
	}

	sourceFilePath := filepath.Join(currentScriptDirectory, filename)
	outputFilePath := filepath.Join(currentScriptDirectory, strings.Replace(filename, ".ogg", "OggBase64.tsx", 1))

	// Read the OGG file
	oggContent, err := os.ReadFile(sourceFilePath)
	if err != nil {
		fmt.Println("Error reading file:", err)
		return
	}

	// Encode the OGG content to Base64
	base64Data := base64.StdEncoding.EncodeToString(oggContent)

	// Generate the TypeScript file content
	generatedFileContent := fmt.Sprintf(
		"// Code generated by convertOggToBase64.go; DO NOT EDIT.\n"+
			"\n"+
			"export const data = 'data:audio/ogg;base64,%s';\n",
		base64Data,
	)

	// Write the generated content to the output file
	err = os.WriteFile(outputFilePath, []byte(generatedFileContent), 0644)
	if err != nil {
		fmt.Println("Error writing file:", err)
		return
	}
}

func main() {
	generate("notification0.ogg")

	fmt.Println()
	fmt.Println("All OGG files have been generated.")
}
